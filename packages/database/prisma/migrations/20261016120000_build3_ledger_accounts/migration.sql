-- Build 3 Slice 2: per-business ledger accounts (ADR-009 sections 4 to 6, 11
-- and 29; Plan 005 S2).
--
-- Forward-only and atomic: like the Build 2 stocktake migration, this file
-- carries its own BEGIN/COMMIT, because `prisma migrate deploy` (Prisma 7.10)
-- does not run a migration file in one transaction. Any failing statement
-- aborts the whole file and nothing persists.
--
-- Additive only: one new table, its keys, CHECKs and grants. No existing table
-- is altered and no row is written. Charts are provisioned by the application
-- (business creation, and the idempotent operator command for businesses that
-- already exist; maintainer decision M16), never backfilled here.
--
-- Journal entries and lines are deliberately absent: every journal entry needs
-- exactly one typed source column (ADR-009 section 13), and the first source
-- columns are introduced by the valuation slice (S3), which creates both tables
-- with them (maintainer decision, 2026-10-16).
--
-- Order: A the table; B its keys and tenant foreign key; C the CHECKs; D
-- privileges.

BEGIN;

-- A. CreateTable
CREATE TABLE "ledger_accounts" (
    "business_id" UUID NOT NULL,
    "id" UUID NOT NULL,
    "code" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "type" TEXT NOT NULL,
    "normal_balance" TEXT NOT NULL,
    "system_role" TEXT,
    "template_version" INTEGER NOT NULL,
    "status" TEXT NOT NULL,
    "created_at" TIMESTAMPTZ(3) NOT NULL,

    CONSTRAINT "ledger_accounts_pkey" PRIMARY KEY ("id")
);

-- B. CreateIndex: the target of later composite tenant references (journal lines).
CREATE UNIQUE INDEX "ledger_accounts_business_id_id_key" ON "ledger_accounts"("business_id", "id");

-- B. CreateIndex: a display code is unique per business.
CREATE UNIQUE INDEX "ledger_accounts_business_id_code_key" ON "ledger_accounts"("business_id", "code");

-- B. CreateIndex: exactly one account per system role per business (ADR-009
-- section 5). NULL roles (future user accounts) are not constrained here.
CREATE UNIQUE INDEX "ledger_accounts_business_id_system_role_key" ON "ledger_accounts"("business_id", "system_role");

-- B. AddForeignKey
ALTER TABLE "ledger_accounts" ADD CONSTRAINT "ledger_accounts_business_id_fkey" FOREIGN KEY ("business_id") REFERENCES "businesses"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;

-- ---------------------------------------------------------------------------
-- Custom SQL (hand-written and reviewed; not generated by Prisma). Every
-- object here is listed in scripts/verify-schema.mjs. RLS stays off; there
-- are no triggers or functions.
-- ---------------------------------------------------------------------------

-- C. Account shape (ADR-009 section 4): one of the six account types; the
-- normal balance follows from the type (ASSET, CONTRA_REVENUE and EXPENSE are
-- DEBIT; LIABILITY, EQUITY and REVENUE are CREDIT); a system role, when set,
-- is one of the thirteen Build 3 roles and has the type ADR-009 section 5
-- assigns it; a positive template version; ACTIVE only in Build 3 (no archive
-- without account management); a trimmed code of 1..20 and name of 1..120
-- characters (display data only).
ALTER TABLE "ledger_accounts"
    ADD CONSTRAINT "ledger_accounts_type_valid" CHECK ("type" IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'CONTRA_REVENUE', 'EXPENSE')),
    ADD CONSTRAINT "ledger_accounts_normal_balance_valid" CHECK ("normal_balance" IN ('DEBIT', 'CREDIT')),
    ADD CONSTRAINT "ledger_accounts_normal_balance_for_type" CHECK (
        ("type" IN ('ASSET', 'CONTRA_REVENUE', 'EXPENSE') AND "normal_balance" = 'DEBIT')
        OR ("type" IN ('LIABILITY', 'EQUITY', 'REVENUE') AND "normal_balance" = 'CREDIT')
    ),
    ADD CONSTRAINT "ledger_accounts_system_role_valid" CHECK ("system_role" IS NULL OR "system_role" IN (
        'CASH_ON_HAND', 'BANK_TRANSFER_PENDING', 'POS_CARD_CLEARING', 'OTHER_TENDER_CLEARING', 'INVENTORY',
        'SALES_REVENUE', 'SALES_DISCOUNTS', 'TAX_PAYABLE', 'COST_OF_GOODS_SOLD', 'INVENTORY_SHRINKAGE',
        'INVENTORY_GAIN', 'OPENING_BALANCE_EQUITY', 'GOODS_RECEIVED_NOT_INVOICED'
    )),
    ADD CONSTRAINT "ledger_accounts_system_role_type" CHECK (
        "system_role" IS NULL
        OR ("system_role" IN ('CASH_ON_HAND', 'BANK_TRANSFER_PENDING', 'POS_CARD_CLEARING', 'OTHER_TENDER_CLEARING', 'INVENTORY') AND "type" = 'ASSET')
        OR ("system_role" IN ('TAX_PAYABLE', 'GOODS_RECEIVED_NOT_INVOICED') AND "type" = 'LIABILITY')
        OR ("system_role" = 'OPENING_BALANCE_EQUITY' AND "type" = 'EQUITY')
        OR ("system_role" IN ('SALES_REVENUE', 'INVENTORY_GAIN') AND "type" = 'REVENUE')
        OR ("system_role" = 'SALES_DISCOUNTS' AND "type" = 'CONTRA_REVENUE')
        OR ("system_role" IN ('COST_OF_GOODS_SOLD', 'INVENTORY_SHRINKAGE') AND "type" = 'EXPENSE')
    ),
    ADD CONSTRAINT "ledger_accounts_template_version_positive" CHECK ("template_version" >= 1),
    ADD CONSTRAINT "ledger_accounts_status_valid" CHECK ("status" = 'ACTIVE'),
    ADD CONSTRAINT "ledger_accounts_code_valid" CHECK (char_length("code") BETWEEN 1 AND 20 AND "code" = btrim("code")),
    ADD CONSTRAINT "ledger_accounts_name_valid" CHECK (char_length("name") BETWEEN 1 AND 120 AND "name" = btrim("name"));

-- D. Privileges (ADR-009 sections 4 and 11): the application role reads and
-- inserts accounts only. No UPDATE, DELETE or TRUNCATE; accounts are never
-- renamed, recoded, archived or deleted in Build 3.
GRANT SELECT, INSERT ON "ledger_accounts" TO tali_app;

COMMIT;
